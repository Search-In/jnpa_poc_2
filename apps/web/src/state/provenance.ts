export interface BoardSummary {
  /** The single word the header chip shows. */
  label: 'LIVE' | 'MIXED' | 'SIMULATED';
  real: number;
  mixed: number;
  simulated: number;
  /** Sentence for the chip's tooltip. */
  detail: string;
}

/**
 * Roll the per-screen map up into the one thing the header can fit.
 *
 * LIVE only when NOTHING is simulated — a single simulated screen makes the
 * board mixed, because a viewer who trusts the header on one tab will trust it
 * on all of them. STATIC screens (methodology, model cards) are excluded from
 * the count entirely: they are documents, and counting them either way would
 * move a number that describes data sources.
 */
export function boardSummary(screens: ScreenProvenance[]): BoardSummary {
  const counted = screens.filter((s) => s.provenance !== 'STATIC');
  const real = counted.filter((s) => s.provenance === 'REAL').length;
  const mixed = counted.filter((s) => s.provenance === 'MIXED').length;
  const simulated = counted.filter(
    (s) => s.provenance === 'SIMULATED' || s.provenance === 'BROWSER',
  ).length;

  const label: BoardSummary['label'] =
    real > 0 && mixed === 0 && simulated === 0 ? 'LIVE'
      : real === 0 && mixed === 0 ? 'SIMULATED'
        : 'MIXED';

  const parts = [
    real ? `${real} real` : '',
    mixed ? `${mixed} mixed` : '',
    simulated ? `${simulated} simulated` : '',
  ].filter(Boolean);

  return {
    label,
    real,
    mixed,
    simulated,
    detail: `${parts.join(' · ')} of ${counted.length} data screens. `
      + 'Every screen states its own source; click for the breakdown.',
  };
}

/**
 * What the KPI strip is entitled to claim (UC2-064, blocker B).
 *
 * The strip renders above every tab and, alone among the panels, carried no
 * provenance at all — seven tender-exact KPIs with nothing saying where they
 * came from. Derived from the guarded delegation list rather than written out,
 * so making `getKPIs` real (UC2-034/039) flips this line automatically instead
 * of leaving a stale "simulated" caption over real numbers.
 */
export const KPI_IS_SIMULATED: boolean =
  (SIMULATOR_BACKED_READS as readonly string[]).includes('getKPIs');

export const KPI_PROVENANCE: string = KPI_IS_SIMULATED
  ? 'Computed from the simulator dataset — not from the ingested corpus. '
    + 'Binding these to real events is UC2-034/039.'
  : 'Computed from the ingested corpus via POC-3.';

/** Colour role for a provenance, resolved by the caller against the theme. */
export function provenanceTone(p: Provenance): 'good' | 'warn' | 'muted' {
  if (p === 'REAL') return 'good';
  if (p === 'MIXED') return 'warn';
  return 'muted';
}
