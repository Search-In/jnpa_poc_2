/**
 * What is actually serving each screen (ticket UC2-064).
 *
 * THE PROBLEM THIS SOLVES
 * -----------------------
 * The header carried one word for the whole board — `adapter.mode`, rendered as
 * LIVE or SIMULATED — and that word is wrong on every screen, because the board
 * is genuinely mixed and always has been.
 *
 * In the deployed build `VITE_DATA_MODE` is never set (the CI job does not pass
 * it), so the base adapter is the simulator and the chip reads SIMULATED. But
 * `VITE_CARGO_SOURCE` defaults to `poc3`, so Import, Export, Movements, CFS/ECY
 * and Data Quality are serving the real ingested corpus and say so on their own
 * `SourceBadge`. An evaluator reads SIMULATED in the header, then reads
 * "Data Source: ICEGATE · CHPOI03" two inches below it. One of them is lying and
 * they cannot tell which.
 *
 * Understating is not the safe direction either. Calling real customs documents
 * simulated throws away the strongest evidence in the bid.
 *
 * WHAT IT IS
 * ----------
 * A declarative map from tab to what serves it, evaluated against the runtime
 * configuration. Deliberately data, not React, so the guard test can assert it
 * against the adapter that actually does the delegating — see
 * `SIMULATOR_BACKED_READS`, and `test/provenance.test.ts` which reads
 * `poc3-cargo-adapter.ts` and fails if the two drift apart. A provenance map
 * maintained by hand is a provenance map that goes stale, and a stale one is
 * worse than none: it is a confident claim nobody re-checks.
 */
import type { TabId } from '../sim/scenarioPlayer.js';

/**
 * The `DataAdapter` reads `Poc3CargoAdapter` hands straight to the adapter below
 * it — i.e. the ones POC-3 does NOT re-source, which on a default build means
 * the simulator.
 *
 * ⚠ Kept in sync by `test/provenance.test.ts`, which extracts every
 * `return this.base.X` from the adapter source and demands this set matches. If
 * you make one of these real, the test fails until this list and the tab map
 * below are updated — which is the point.
 */
export const SIMULATOR_BACKED_READS = [
  'getFacilities',
  'getTerminals',
  'getGateOps',
  'getGateQueueForecast',
  'getPendency',
  'getRailSide',
  'getRakeForecast',
  'getITRHO',
  'getEmptyPool',
  'getKPIs',
  'getNotifications',
  'getIntegrationHealth',
  'runScenario',
] as const;

/** How a screen's data is produced. Ordered worst-to-best for summarising. */
export type Provenance =
  /** Held only in this browser — localStorage / BroadcastChannel. */
  | 'BROWSER'
  /** Generated by the schema-accurate simulator. No external system involved. */
  | 'SIMULATED'
  /** Some panels real, some simulated. The detail says which. */
  | 'MIXED'
  /** Served by a real backend over real ingested data. */
  | 'REAL'
  /** Fixed artefacts — exported model metrics, written methodology. */
  | 'STATIC';

export interface ScreenProvenance {
  tab: TabId;
  provenance: Provenance;
  /** One line an operator can read aloud. */
  summary: string;
  /** Named real parts, when MIXED. */
  real?: string;
  /** Named simulated parts, when MIXED. */
  simulated?: string;
}

/** The runtime facts the map is evaluated against. */
export interface ProvenanceContext {
  /** `VITE_CARGO_SOURCE` — poc3 | mock | reference. */
  cargoSource: string;
  /** `adapter.mode` — the base adapter, mock | live. */
  baseMode: string;
  /**
   * Whether any connector service answered its own /health. Null while the probe
   * is still in flight — rendered as "checking", never optimistically as live.
   */
  connectorsLive: boolean | null;
}

const POC3 = (c: ProvenanceContext) => c.cargoSource === 'poc3';

